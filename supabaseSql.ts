/**
 * Supabase SQL Editor에서 실행할 수 있는 cafe_menu 테이블 생성 및 테스트 데이터 INSERT 쿼리문
 */

export const SUPABASE_SQL_SCRIPT = `-- ==========================================================
-- 1. cafe_menu 테이블 생성 쿼리문 (Supabase SQL Editor용)
-- 바이브 카페 주문서 항목에 맞춘 컬럼 정의
-- ==========================================================

-- 기존 테이블이 있을 경우 삭제 (필요한 경우만 주석 해제)
-- DROP TABLE IF EXISTS public.cafe_menu;

CREATE TABLE IF NOT EXISTS public.cafe_menu (
    -- 고유 식별자 (자동 생성 기본키)
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    
    -- 1. 주문자 이름 (필수, text)
    customer_name TEXT NOT NULL,
    
    -- 2. 전화번호 (연락처, tel)
    phone_number VARCHAR(30),
    
    -- 3. 음료 이름 및 기본 가격 (선택된 음료)
    drink_name VARCHAR(50) NOT NULL,
    drink_price INTEGER NOT NULL,
    
    -- 4. 사이즈 (S: 0원, M: 500원, L: 1,000원)
    size VARCHAR(10) NOT NULL DEFAULT 'M',
    size_price INTEGER NOT NULL DEFAULT 500,
    
    -- 5. 추가 옵션 목록 (텍스트 배열: 샷 추가, 크림 추가, 시럽 추가, 디카페인 등)
    options TEXT[] DEFAULT '{}',
    options_price INTEGER NOT NULL DEFAULT 0,
    
    -- 6. 수량 (1 ~ 10잔)
    quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity >= 1 AND quantity <= 10),
    
    -- 7. 고객 요청사항 (textarea)
    requests TEXT,
    
    -- 최종 예상/결제 금액 (원 단위)
    total_price INTEGER NOT NULL,
    
    -- 주문 처리 상태 (접수완료, 제조중, 제조완료, 픽업완료)
    order_status VARCHAR(20) NOT NULL DEFAULT '접수완료',
    
    -- 주문 생성 시각 (기본값 현재 시각)
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 테이블 및 주요 컬럼에 대한 한국어 설명 주석 (Comment)
COMMENT ON TABLE public.cafe_menu IS '바이브 카페 고객 주문 및 메뉴 주문 접수 테이블';
COMMENT ON COLUMN public.cafe_menu.customer_name IS '주문자 이름 (필수 입력)';
COMMENT ON COLUMN public.cafe_menu.phone_number IS '주문자 연락처 전화번호';
COMMENT ON COLUMN public.cafe_menu.drink_name IS '선택한 음료 명칭';
COMMENT ON COLUMN public.cafe_menu.drink_price IS '음료 기본 단가 (원)';
COMMENT ON COLUMN public.cafe_menu.size IS '선택 사이즈 (S, M, L)';
COMMENT ON COLUMN public.cafe_menu.size_price IS '사이즈에 따른 추가 금액';
COMMENT ON COLUMN public.cafe_menu.options IS '선택한 추가 옵션 배열';
COMMENT ON COLUMN public.cafe_menu.options_price IS '추가 옵션 총 금액';
COMMENT ON COLUMN public.cafe_menu.quantity IS '주문 수량 (1~10)';
COMMENT ON COLUMN public.cafe_menu.requests IS '요청사항 메모';
COMMENT ON COLUMN public.cafe_menu.total_price IS '최종 계산된 총 주문 금액';
COMMENT ON COLUMN public.cafe_menu.order_status IS '주문 진행 상태';

-- ==========================================================
-- 2. Row Level Security (RLS) 정책 설정 (선택 사항)
-- Supabase 클라이언트에서 자유롭게 조회/등록할 수 있도록 활성화
-- ==========================================================
ALTER TABLE public.cafe_menu ENABLE ROW LEVEL SECURITY;

-- 누구나 주문을 생성(INSERT)할 수 있도록 허용하는 정책
CREATE POLICY "누구나 주문 등록 가능" 
ON public.cafe_menu 
FOR INSERT 
WITH CHECK (true);

-- 누구나 주문 내역을 조회(SELECT)할 수 있도록 허용하는 정책
CREATE POLICY "누구나 주문 내역 조회 가능" 
ON public.cafe_menu 
FOR SELECT 
USING (true);

-- 누구나 주문 상태를 변경(UPDATE)할 수 있도록 허용하는 정책
CREATE POLICY "누구나 주문 수정 가능" 
ON public.cafe_menu 
FOR UPDATE 
USING (true)
WITH CHECK (true);

-- 누구나 주문을 삭제(DELETE)할 수 있도록 허용하는 정책
CREATE POLICY "누구나 주문 삭제 가능" 
ON public.cafe_menu 
FOR DELETE 
USING (true);

-- ==========================================================
-- 3. 테스트용 가짜 데이터 1건 INSERT 쿼리문
-- 홍길동 고객님의 카페라떼 M사이즈(샷 추가 1개) 1잔 (5,000원)
-- ==========================================================
INSERT INTO public.cafe_menu (
    customer_name,
    phone_number,
    drink_name,
    drink_price,
    size,
    size_price,
    options,
    options_price,
    quantity,
    requests,
    total_price,
    order_status
) VALUES (
    '홍길동',
    '010-1234-5678',
    '카페라떼',
    4000,
    'M',
    500,
    ARRAY['샷 추가'],
    500,
    1,
    '얼음 적게 덜 차갑게 부탁드립니다 ☕',
    5000,
    '접수완료'
);
`;
